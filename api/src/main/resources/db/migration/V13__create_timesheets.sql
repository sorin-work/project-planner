create table timesheets (
    id              bigint generated by default as identity primary key,
    organisation_id bigint      not null references organisations (id) on delete cascade,
    user_id         bigint      not null references users (id) on delete cascade,
    week_start      date        not null,
    status          varchar(16) not null default 'DRAFT',
    submitted_at    timestamp with time zone,
    reviewed_at     timestamp with time zone,
    reviewed_by     bigint      references users (id) on delete set null,
    review_note     varchar(1000),
    constraint uq_timesheets_user_week unique (organisation_id, user_id, week_start),
    constraint ck_timesheets_status check (status in ('DRAFT', 'SUBMITTED', 'APPROVED', 'REJECTED'))
);

create index ix_timesheets_org_status on timesheets (organisation_id, status);
