-- A baseline is a saved copy of a plan's dates: what was agreed, to compare the
-- plan with later. Rows are written once and never changed.
create table baselines (
    id            bigint generated by default as identity primary key,
    project_id    bigint       not null references projects (id) on delete cascade,
    name          varchar(120) not null,
    -- The name trimmed and in lower case: two baselines of a project cannot share it.
    name_key      varchar(120) not null,
    -- The project's id on the one baseline that comparisons use unless another is picked,
    -- null on the others. Unique, so a project has one reference at most. (A partial index
    -- "unique (project_id) where is_reference" would say it better, but H2 has none.)
    reference_of  bigint,
    project_start date,
    project_end   date,
    created_by    bigint       references users (id) on delete set null,
    created_at    timestamp with time zone not null,
    constraint uq_baselines_name unique (project_id, name_key),
    constraint uq_baselines_reference unique (reference_of),
    constraint ck_baselines_reference check (reference_of is null or reference_of = project_id)
);

create index ix_baselines_project on baselines (project_id);

-- The tasks as they were. The task, parent and phase ids are plain values without
-- a foreign key, as in activity_log, and the title and phase name are copied, so
-- that a task deleted later still shows up as removed.
create table baseline_tasks (
    id             bigint generated by default as identity primary key,
    baseline_id    bigint       not null references baselines (id) on delete cascade,
    task_id        bigint       not null,
    parent_task_id bigint,
    phase_id       bigint,
    phase_name     varchar(120),
    title          varchar(200) not null,
    start_date     date,
    due_date       date,
    estimate_hours numeric(8, 2),
    milestone      boolean      not null default false,
    constraint uq_baseline_tasks unique (baseline_id, task_id)
);

-- The phases as they were, with their dates. Plain ids again, and the name copied.
create table baseline_phases (
    id          bigint generated by default as identity primary key,
    baseline_id bigint       not null references baselines (id) on delete cascade,
    phase_id    bigint       not null,
    name        varchar(120) not null,
    start_date  date,
    end_date    date,
    constraint uq_baseline_phases unique (baseline_id, phase_id)
);
