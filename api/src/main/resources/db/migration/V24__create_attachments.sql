-- Files attached to tasks. The bytes are on disk under ATTACHMENTS_DIR, saved under
-- storage_key, a random name the server made, never under the uploaded name. The row
-- goes with its task. The file does not go by itself: the API deletes it when it
-- deletes the task or the project, and a sweep removes any file that has no row.
create table attachments (
    id              bigint generated by default as identity primary key,
    organisation_id bigint       not null references organisations (id) on delete cascade,
    task_id         bigint       not null references tasks (id) on delete cascade,
    uploader_id     bigint       references users (id) on delete set null,
    file_name       varchar(255) not null,
    -- What the server found the file to be, not what the browser said it was.
    content_type    varchar(100) not null,
    size_bytes      bigint       not null,
    storage_key     varchar(64)  not null,
    created_at      timestamp with time zone not null,
    constraint uq_attachments_storage_key unique (storage_key),
    constraint ck_attachments_size check (size_bytes >= 0)
);

create index ix_attachments_task on attachments (task_id);
create index ix_attachments_organisation on attachments (organisation_id);
