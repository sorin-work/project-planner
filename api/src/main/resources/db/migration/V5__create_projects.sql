create table projects (
    id              bigint generated by default as identity primary key,
    organisation_id bigint        not null references organisations (id) on delete cascade,
    client_id       bigint        references clients (id) on delete set null,
    name            varchar(120)  not null,
    code            varchar(16)   not null,
    description     varchar(4000),
    status          varchar(16)   not null default 'PLANNED',
    start_date      date,
    end_date        date,
    budget_hours    numeric(10, 2),
    budget_amount   numeric(12, 2),
    hourly_rate     numeric(10, 2),
    color           varchar(7)    not null default '#4f6bed',
    created_at      timestamp with time zone not null,
    updated_at      timestamp with time zone not null,
    constraint uq_projects_org_code unique (organisation_id, code),
    constraint ck_projects_status check (status in ('PLANNED', 'ACTIVE', 'ON_HOLD', 'DONE')),
    constraint ck_projects_dates check (end_date is null or start_date is null or end_date >= start_date)
);

create index ix_projects_org on projects (organisation_id);
