-- Days nobody in the organisation works, and days one person is away. A holiday takes the
-- day out of every working-day count; time off only lowers that person's capacity.
create table holidays (
    id              bigint generated by default as identity primary key,
    organisation_id bigint       not null references organisations (id) on delete cascade,
    holiday_date    date         not null,
    name            varchar(120) not null,
    constraint uq_holidays_org_date unique (organisation_id, holiday_date)
);

create table time_off (
    id              bigint generated by default as identity primary key,
    organisation_id bigint        not null references organisations (id) on delete cascade,
    user_id         bigint        not null references users (id) on delete cascade,
    first_day       date          not null,
    last_day        date          not null,
    note            varchar(500),
    created_at      timestamp with time zone not null,
    constraint ck_time_off_days check (last_day >= first_day)
);

create index ix_time_off_org_user on time_off (organisation_id, user_id);
