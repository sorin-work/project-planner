-- The outbox of notification mails. A notification with emailed_at null still has to be
-- mailed; a failed attempt counts up email_attempts and waits until email_retry_at.
alter table notifications add column emailed_at timestamp with time zone;
alter table notifications add column email_attempts integer default 0 not null;
alter table notifications add column email_retry_at timestamp with time zone;

-- Notifications from before mail are never mailed.
update notifications set emailed_at = created_at;

create index ix_notifications_outbox on notifications (emailed_at, email_retry_at);

-- How each person wants each type of notification. Without a row the default in
-- NotificationPreferences holds.
create table notification_preferences (
    id       bigint generated by default as identity primary key,
    user_id  bigint      not null references users (id) on delete cascade,
    type     varchar(32) not null,
    delivery varchar(8)  not null,
    constraint uq_notification_preferences unique (user_id, type),
    constraint ck_notification_preferences_delivery check (delivery in ('EMAIL', 'IN_APP', 'OFF'))
);
