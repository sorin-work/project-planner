-- One row per person, organisation and day that the morning summary was taken on for. The
-- job inserts it before it sends, so the unique key decides which API instance sends it.
-- sent_at stays null when there was nothing to say or the mail could not be sent.
create table daily_summaries (
    id              bigint generated by default as identity primary key,
    organisation_id bigint not null references organisations (id) on delete cascade,
    user_id         bigint not null references users (id) on delete cascade,
    summary_day     date   not null,
    sent_at         timestamp with time zone,
    constraint uq_daily_summaries unique (organisation_id, user_id, summary_day)
);

-- Automatic timesheet reminders on the first working day of the week, off by default.
-- reminders_sent_on is the day they last went out, so one instance sends them once a day.
alter table organisations add column auto_reminders boolean default false not null;
alter table organisations add column reminders_sent_on date;
