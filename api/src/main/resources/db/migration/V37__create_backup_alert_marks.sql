-- What the backup watch has mailed the operators about: one row per state of the backups
-- and the dump it was about ("LATE:planner-20261120T030000Z.dump"). The unique key lets one
-- instance of the api mail about each change once, and a change of either the state or the
-- dump is news again.
create table backup_alert_marks (
    id      bigint generated by default as identity primary key,
    marker  varchar(300) not null,
    sent_at timestamp with time zone not null,
    constraint uq_backup_alert_marks unique (marker)
);
