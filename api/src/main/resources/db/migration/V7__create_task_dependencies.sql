-- Finish-to-start links: the successor can start once the predecessor is finished
-- (plus an optional lag in working days).
create table task_dependencies (
    id             bigint generated by default as identity primary key,
    predecessor_id bigint  not null references tasks (id) on delete cascade,
    successor_id   bigint  not null references tasks (id) on delete cascade,
    lag_days       integer not null default 0,
    created_at     timestamp with time zone not null,
    constraint uq_task_dependencies unique (predecessor_id, successor_id),
    constraint ck_task_dependencies_self check (predecessor_id <> successor_id),
    constraint ck_task_dependencies_lag check (lag_days >= 0)
);

create index ix_task_dependencies_successor on task_dependencies (successor_id);
