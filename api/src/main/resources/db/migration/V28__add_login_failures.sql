-- Wrong passwords in a row for one account from one client address, and when the last one
-- was typed. A few pass, then each further try from that address for that account waits
-- longer. Kept per address, so that somebody trying passwords from one place slows down
-- that place only and never the owner signing in from another. In the database rather than
-- in memory, so that the count holds across a restart and across several copies of the API.
create table login_failures (
    id             bigint generated by default as identity primary key,
    user_id        bigint      not null references users (id) on delete cascade,
    address        varchar(64) not null,
    failures       integer     not null,
    last_failed_at timestamp with time zone not null,
    constraint uq_login_failures_user_address unique (user_id, address)
);

-- Wrong passwords for the account from every address together. It never refuses a try:
-- past a number of them, a new address gets fewer free tries before it has to wait.
alter table users add column failed_logins integer default 0 not null;
alter table users add column last_failed_login_at timestamp with time zone;
