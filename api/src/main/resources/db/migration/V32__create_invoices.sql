-- Invoices made from approved, billable time. Amounts are in minor units (cents) of the
-- invoice's currency, copied onto it when it is made, as are the rates and the names on its
-- lines: an issued invoice never changes, whatever happens to rates, the currency, a task or
-- a person later. The number is taken when the invoice is issued, one sequence per
-- organisation without gaps; a draft has none. A correction is a credit note: an invoice of
-- its own kind that points at the one it cancels, at most one per invoice.
create table invoices (
    id                 bigint generated by default as identity primary key,
    organisation_id    bigint        not null references organisations (id) on delete cascade,
    client_id          bigint        not null references clients (id),
    client_name        varchar(200)  not null,
    kind               varchar(16)   not null default 'INVOICE',
    credits_invoice_id bigint        references invoices (id),
    number             integer,
    status             varchar(16)   not null default 'DRAFT',
    period_from        date          not null,
    period_to          date          not null,
    currency           varchar(3)    not null,
    group_by           varchar(16)   not null,
    tax_rate_bp        integer       not null default 0,
    subtotal_cents     bigint        not null default 0,
    tax_cents          bigint        not null default 0,
    total_cents        bigint        not null default 0,
    notes              varchar(2000),
    created_at         timestamp with time zone not null,
    issued_at          timestamp with time zone,
    constraint uq_invoices_number unique (organisation_id, number),
    constraint uq_invoices_credit unique (credits_invoice_id),
    constraint ck_invoices_status check (status in ('DRAFT', 'ISSUED')),
    constraint ck_invoices_kind check (kind in ('INVOICE', 'CREDIT_NOTE')),
    constraint ck_invoices_tax check (tax_rate_bp between 0 and 10000)
);

create index ix_invoices_org on invoices (organisation_id, status);

create table invoice_lines (
    id           bigint generated by default as identity primary key,
    invoice_id   bigint        not null references invoices (id) on delete cascade,
    position     integer       not null,
    project_id   bigint        references projects (id) on delete set null,
    project_name varchar(200)  not null,
    task_title   varchar(300),
    person_name  varchar(200),
    description  varchar(500)  not null,
    minutes      integer       not null,
    rate_cents   bigint        not null,
    amount_cents bigint        not null
);

create index ix_invoice_lines_invoice on invoice_lines (invoice_id);
create index ix_invoice_lines_project on invoice_lines (project_id);

-- The line a time entry is billed on. One column, so an entry is on one line at most and is
-- never invoiced twice. A draft that is deleted, or a line taken off it, releases its
-- entries through the foreign key; a credit note releases them by clearing it.
alter table time_entries add column invoice_line_id bigint references invoice_lines (id) on delete set null;
create index ix_time_entries_invoice_line on time_entries (invoice_line_id);
