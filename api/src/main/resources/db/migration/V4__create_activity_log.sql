-- Append-only history. Project and task ids are kept as plain values so entries
-- survive when the project or task they mention is deleted.
create table activity_log (
    id              bigint generated by default as identity primary key,
    organisation_id bigint       not null references organisations (id) on delete cascade,
    project_id      bigint,
    task_id         bigint,
    actor_id        bigint       references users (id) on delete set null,
    action          varchar(48)  not null,
    summary         varchar(500) not null,
    created_at      timestamp with time zone not null
);

create index ix_activity_log_org on activity_log (organisation_id, created_at);
create index ix_activity_log_project on activity_log (project_id, created_at);
