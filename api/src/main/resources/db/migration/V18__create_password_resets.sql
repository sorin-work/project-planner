-- Links to set a new password. Only a hash of the token is kept: the token itself is
-- in the mail and nowhere else.
create table password_resets (
    id         bigint generated by default as identity primary key,
    user_id    bigint      not null references users (id) on delete cascade,
    token_hash varchar(64) not null,
    created_at timestamp with time zone not null,
    expires_at timestamp with time zone not null,
    used_at    timestamp with time zone,
    constraint uq_password_resets_token_hash unique (token_hash)
);

create index ix_password_resets_user on password_resets (user_id);

-- Every login token carries the version of its account. A change or reset of the password
-- counts it up, and a token with an older version is no longer accepted. The time of the
-- last change is kept to be shown.
alter table users add column token_version integer default 0 not null;
alter table users add column password_changed_at timestamp with time zone;

-- The link in an invitation mail: a hash of its token, when it stops working and when it
-- was last sent.
alter table invitations add column token_hash varchar(64);
alter table invitations add column token_expires_at timestamp with time zone;
alter table invitations add column sent_at timestamp with time zone;
alter table invitations add constraint uq_invitations_token_hash unique (token_hash);
