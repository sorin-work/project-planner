create table organisations (
    id                   bigint generated by default as identity primary key,
    name                 varchar(120) not null,
    currency             varchar(3)   not null default 'EUR',
    timezone             varchar(64)  not null default 'UTC',
    default_hourly_rate  numeric(10, 2) not null default 0,
    created_at           timestamp with time zone not null
);

create table memberships (
    id                    bigint generated by default as identity primary key,
    organisation_id       bigint      not null references organisations (id) on delete cascade,
    user_id               bigint      not null references users (id) on delete cascade,
    role                  varchar(16) not null,
    hourly_rate           numeric(10, 2),
    weekly_capacity_hours numeric(5, 2) not null default 40,
    -- For client viewers: the client whose projects they can see.
    client_id             bigint,
    created_at            timestamp with time zone not null,
    constraint uq_memberships_org_user unique (organisation_id, user_id),
    constraint ck_memberships_role check (role in ('OWNER', 'MANAGER', 'MEMBER', 'CLIENT'))
);

create index ix_memberships_user on memberships (user_id);
