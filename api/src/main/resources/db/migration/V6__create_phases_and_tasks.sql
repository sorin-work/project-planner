create table phases (
    id         bigint generated by default as identity primary key,
    project_id bigint       not null references projects (id) on delete cascade,
    name       varchar(120) not null,
    position   integer      not null default 0,
    start_date date,
    end_date   date
);

create index ix_phases_project on phases (project_id);

create table tasks (
    id             bigint generated by default as identity primary key,
    project_id     bigint        not null references projects (id) on delete cascade,
    phase_id       bigint        references phases (id) on delete set null,
    parent_id      bigint        references tasks (id) on delete cascade,
    title          varchar(200)  not null,
    description    varchar(10000),
    status         varchar(16)   not null default 'TODO',
    priority       varchar(16)   not null default 'MEDIUM',
    estimate_hours numeric(8, 2),
    start_date     date,
    due_date       date,
    assignee_id    bigint        references users (id) on delete set null,
    milestone      boolean       not null default false,
    completed_at   timestamp with time zone,
    created_at     timestamp with time zone not null,
    updated_at     timestamp with time zone not null,
    constraint ck_tasks_status check (status in ('TODO', 'IN_PROGRESS', 'IN_REVIEW', 'DONE')),
    constraint ck_tasks_priority check (priority in ('LOW', 'MEDIUM', 'HIGH', 'URGENT')),
    constraint ck_tasks_dates check (due_date is null or start_date is null or due_date >= start_date)
);

create index ix_tasks_project on tasks (project_id);
create index ix_tasks_assignee on tasks (assignee_id);
create index ix_tasks_parent on tasks (parent_id);
